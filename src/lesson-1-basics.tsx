//; }

//; export default App;
//; Один из компонентов должен быть основным - тем, к которому добавляются остальные компоненты. В React по умолчанию таким компонентом будет компонент App. К этому компоненту будут подключаться другие компоненты. Как это делается - мы разберем далее в учебнике.

